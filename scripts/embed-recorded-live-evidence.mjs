import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(
  root,
  "apps",
  "web",
  "server",
  "embedded-recorded-live-evidence.generated.ts",
);

function sha256(value) {
  return createHash("sha256").update(value, "utf8").digest("hex");
}

async function readVerifiedArtifact({
  evidenceDirectory,
  runPattern,
  artifactName,
}) {
  const latestPath = path.join(evidenceDirectory, "latest-run.txt");
  const runId = (await readFile(latestPath, "utf8")).trim();
  if (!runPattern.test(runId)) {
    throw new Error(`Unsafe recorded evidence run pointer: ${runId}`);
  }
  const runDirectory = path.join(evidenceDirectory, runId);
  const [body, manifest] = await Promise.all([
    readFile(path.join(runDirectory, artifactName), "utf8"),
    readFile(path.join(runDirectory, "manifest.sha256"), "utf8"),
  ]);
  const expectedManifest = `${sha256(body)}  ${artifactName}`;
  if (manifest.trim() !== expectedManifest) {
    throw new Error(`Manifest verification failed for ${artifactName}`);
  }
  return { runId, body, manifest: manifest.trim() };
}

const live = await readVerifiedArtifact({
  evidenceDirectory: path.join(
    root,
    "artifacts",
    "evidence",
    "safecommit-database-live",
  ),
  runPattern: /^safecommit-live-\d{8}T\d{9}Z$/u,
  artifactName: "database-live-evidence.json",
});
const approval = await readVerifiedArtifact({
  evidenceDirectory: path.join(
    root,
    "artifacts",
    "evidence",
    "safecommit-database-approval",
  ),
  runPattern: /^safecommit-approval-\d{8}T\d{9}Z$/u,
  artifactName: "database-approval.json",
});

const source = `// Generated by scripts/embed-recorded-live-evidence.mjs.
// Contains redacted, manifest-verified public evidence only.
export const liveRunId = ${JSON.stringify(live.runId)};
export const liveArtifactBody = ${JSON.stringify(live.body)};
export const liveArtifactManifest = ${JSON.stringify(live.manifest)};
export const approvalRunId = ${JSON.stringify(approval.runId)};
export const approvalArtifactBody = ${JSON.stringify(approval.body)};
export const approvalArtifactManifest = ${JSON.stringify(approval.manifest)};
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");
console.log(`Embedded ${live.runId} and ${approval.runId}`);
